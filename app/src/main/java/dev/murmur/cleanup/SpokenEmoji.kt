    // Longest names first so "red heart" wins over "heart"
    private val PATTERN = Regex(
        """(?<![\w'’])(""" + NAMES.keys.sortedByDescending { it.length }.joinToString("|") { name -> name.split(' ').joinToString("\\s+") { Regex.escape(it) } } +
            """)\s+(?:emojis?|emoticons?)\b\.?""",
        RegexOption.IGNORE_CASE,
    )

    /** The emoji for a spoken name ("melting face"), or null. */
    fun lookup(name: String): String? = NAMES[name.lowercase().replace('’', '\'')]

    fun apply(text: String): String {
        if (!text.contains("emoji", ignoreCase = true) && !text.contains("emoticon", ignoreCase = true)) return text
        return PATTERN.replace(text) { m ->
            NAMES[m.groupValues[1].lowercase().replace(Regex("""\s+"""), " ").replace('’', '\'')] ?: m.value
        }.replace(Regex(""" {2,}"""), " ").trim()
    }
